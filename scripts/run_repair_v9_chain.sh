#!/usr/bin/env bash
# repair_v9 chain: the WP4 ages become the headline table (issue #21; owner
# decisions of 2026-10-07).  A and C carry their Phase A' test-c spectroscopic
# posteriors, B the A + C product (not measured for B).  Nothing else changes.
#
# Pre-registered BEFORE this chain ran: provenance/repair_v9_prereg.json
# (integrity checks I1-I5, predictions V1-V5, adoption rule, the age scan).
# Adoption: ADOPTED = "repair_v9" in scripts/chain.py iff I1-I5 pass.  This
# runner never edits chain.py.
#
# What runs, in four phases (each step skips if its output exists, so the
# runner is resumable; nothing at repair_v8 or earlier is overwritten):
#   A  WP4: anchors + mass posteriors for repair_v9, the I1 replay and the
#      eleven age-scan points (13 mass jobs in parallel)
#   B  injections: repair_v9 WP5 nodes (162) and WP6 extension (162), the I1
#      injector subset (27 PARSEC R_V 3.1 repair_v7 nodes regenerated) and the
#      scan (11 x 18 single nodes)
#   C  WP5 fits: repair_v9, replay, eleven scan points (in parallel); then the
#      replay and scan ledgers
#   D  repair_v9 WP6-WP12 (the repair_v8 runner's steps, chain repair_v9), the
#      integrity checks and the scoring
#
# Run detached from the repository root:
#   tmux new -d -s repair_v9 "bash scripts/run_repair_v9_chain.sh 2>&1 | tee -a data/processed/repair_v9_logs/chain.log"
set -euo pipefail

export PYTHONPATH=scripts
export WP_REPAIR_VERSION=repair_v5        # WP3 extinction (and nothing else here)
export WP3_ANCHOR_PRIOR_MODE=kriging
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
PY="${PYTHON_BIN:-python3}"
WORKERS="${WORKERS:-28}"
PRE=provenance/repair_v9_prereg.json
LOG=data/processed/repair_v9_logs
mkdir -p "$LOG"

step() { printf '\n=== %s  [%s]\n' "$1" "$(date '+%F %T')"; }
have() { [ -f "$1" ] && echo "    present: $1 (not regenerated)"; }
scan() { printf 'repair_v9_scan%02d' "$1"; }
integrity() { "$PY" scripts/repair_v9_integrity.py "$@"; }

[ -f "$PRE" ] || { echo "missing $PRE -- pre-register first"; exit 1; }
step "0  I3: every pre-registered input and code hash"
integrity I3

# ---------------------------------------------------------------- phase A
step "A1 anchors: repair_v9 (headline ages), replay (repair_v5 ages), scan"
have data/processed/wp4_age_posteriors_repair_v9_scan10.parquet || \
  "$PY" scripts/repair_v9_age_scan.py tables
anchors() {  # age_version output_version
  have "data/processed/wp4_anchor_hrd_$2.parquet" || \
    "$PY" scripts/wp4_anchors_hrd.py --age-version "$1" --extinction-version repair_v5 \
      --output-version "$2" --preregistration "$PRE"
}
anchors repair_v9_headline repair_v9
anchors repair_v5 repair_v9_replay
for i in $(seq 0 10); do anchors "$(scan "$i")" "$(scan "$i")"; done
integrity I1a I2

step "A2 mass posteriors (13 jobs in parallel)"
masses() {  # age_version anchor/output version
  have "data/processed/wp4_mass_posteriors_$2.parquet" || \
    "$PY" scripts/wp4_mass_posteriors_repair.py --age-version "$1" \
      --anchor-version "$2" --output-version "$2" > "$LOG/masses_$2.log" 2>&1
}
pids=()
masses repair_v9_headline repair_v9 & pids+=($!)
masses repair_v5 repair_v9_replay & pids+=($!)
for i in $(seq 0 10); do masses "$(scan "$i")" "$(scan "$i")" & pids+=($!); done
for p in "${pids[@]}"; do wait "$p"; done
integrity I1b

# ---------------------------------------------------------------- phase B
step "B1 I1 injector subset: 27 repair_v7 nodes regenerated by the v9 driver"
have provenance/wp5_injections_agenodes_execution_repair_v9_replay.json || \
  "$PY" scripts/repair_v9_injections.py --kind wp5 --age-version repair_v5 \
    --output-version repair_v9_replay --only PARSEC:3.1 --workers 27
integrity I1c

step "B2 repair_v9 WP5 truth-age nodes (162) and WP6 mass extension (162)"
have provenance/wp5_injections_agenodes_execution_repair_v9.json || \
  "$PY" scripts/repair_v9_injections.py --kind wp5 --age-version repair_v9_headline \
    --output-version repair_v9 --workers "$WORKERS"
have provenance/wp6_massive_injections_execution_repair_v9.json || \
  "$PY" scripts/repair_v9_injections.py --kind wp6ext --age-version repair_v9_headline \
    --output-version repair_v9 --workers "$WORKERS"

step "B3 scan injections: 11 points x 18 single native nodes"
pids=()
for i in $(seq 0 10); do
  v=$(scan "$i")
  ( have "provenance/wp5_injections_agenodes_execution_$v.json" || \
      "$PY" scripts/repair_v9_injections.py --kind wp5 --age-version "$v" \
        --output-version "$v" --workers 3 > "$LOG/inject_$v.log" 2>&1 ) & pids+=($!)
done
for p in "${pids[@]}"; do wait "$p"; done
for i in $(seq 0 10); do "$PY" scripts/repair_v9_age_scan.py check-nodes --index "$i"; done

# ---------------------------------------------------------------- phase C
step "C1 WP5 joint age-k fits: repair_v9, replay, 11 scan points (parallel)"
fit() {  # wp5/mass version, age version, response version, compare
  have "data/processed/wp5_imf_normalization_$1.parquet" || \
    "$PY" scripts/wp5_fit_imf_joint.py --upstream-version repair_v5 --mass-version "$1" \
      --age-version "$2" --response-version "$3" --wp5-version "$1" \
      --compare-version "$4" > "$LOG/fit_$1.log" 2>&1
}
pids=()
fit repair_v9 repair_v9_headline repair_v9 repair_v8 & pids+=($!)
fit repair_v9_replay repair_v5 repair_v7 repair_v8 & pids+=($!)
for i in $(seq 0 10); do v=$(scan "$i"); fit "$v" "$v" "$v" repair_v8 & pids+=($!); done
for p in "${pids[@]}"; do wait "$p"; done
integrity I1d

step "C2 replay ledger (2,000,000 iterations) and scan ledgers (200,000), parallel"
pids=()
( have tables/wp7_ledger_repair_v9_replay.csv || \
    CYGOB2_CHAIN=repair_v9_replay "$PY" scripts/wp7_ledger.py --iterations 2000000 \
      > "$LOG/ledger_replay.log" 2>&1 ) & pids+=($!)
for i in $(seq 0 10); do
  "$PY" scripts/repair_v9_age_scan.py ledger --index "$i" > "$LOG/scan_ledger_$i.log" 2>&1 & pids+=($!)
done
for p in "${pids[@]}"; do wait "$p"; done
integrity I1e
have tables/repair_v9_age_scan.csv || "$PY" scripts/repair_v9_age_scan.py aggregate

# ---------------------------------------------------------------- phase D
export CYGOB2_CHAIN=repair_v9
step "D1 WP6 census, closure (4.0 Msun floor), attribution, living ledger"
"$PY" scripts/wp6_massive_census.py
"$PY" scripts/wp6_closure_test.py --wp5-version repair_v9 --response-version repair_v9
"$PY" scripts/wp6_closure_attribution.py --wp5-version repair_v9
"$PY" scripts/wp6_ledger.py

step "D2 WP7 ledger via the convergence scan (last pass = 2,000,000 iterations)"
"$PY" scripts/wp7_convergence_scan.py
"$PY" scripts/wp7_alpha_headline_adopt.py
"$PY" scripts/wp7_binary_bound.py

step "D3 WP8 cross-checks, WP9 verdict, WP11 isotope forecast (500,000)"
"$PY" scripts/wp8_crosschecks.py
"$PY" scripts/wp9_verdict.py
"$PY" scripts/wp11_isotope_forecast.py --iterations 500000

step "D4 reconciliations and the alpha-plausibility record"
"$PY" scripts/wp4_wp5_age_reconciliation.py
"$PY" scripts/wp5_association_mass_reconciliation.py --compare-version repair_v8
"$PY" scripts/wp5_alpha_plausibility.py

step "D5 WP12 on repair_v9: new hash record, then the analyses"
have provenance/wp12_revision_prereg_repair_v9.json || "$PY" scripts/wp12_prereg.py --chain-record
"$PY" scripts/wp12_gate_landscape.py
"$PY" scripts/wp12_closure_slopes.py
"$PY" scripts/wp12_scenario_score.py
"$PY" scripts/wp12_neighbour_budget.py

step "D6 integrity I3, I4, I5 and the scoring of V1-V5 + adoption rule"
integrity I3 I4 I5
"$PY" scripts/repair_v9_score.py

echo
echo "=== repair_v9 chain complete  [$(date '+%F %T')]"
