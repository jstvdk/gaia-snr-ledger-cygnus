#!/usr/bin/env python3
"""repair_v9 integrity checks I1-I5 (provenance/repair_v9_prereg.json).

Every threshold below is frozen by the pre-registration (this file's SHA-256
is recorded there).  Each check is run by name and merged into
provenance/repair_v9_integrity.json; a check is never loosened after a result
is seen -- a defect in a CHECK is fixed and recorded (brief §8), the science
threshold is not.

  I1  replay: the repair_v9 code path, fed the repair_v5 ages (and the repair_v7
      responses), reproduces repair_v8.  This run crosses platforms (repair_v8 was
      made on macOS arm64; repair_v9 on Linux x86_64), so each part is scored
      EXACT, or WITHIN the stated cross-platform tolerance, or FAIL.
        I1a anchors   wp4_anchor_hrd_repair_v9_replay      vs repair_v8
        I1b masses    wp4_mass_posteriors_repair_v9_replay vs repair_v8
        I1c injector  the 27 PARSEC R_V 3.1 nodes regenerated by
                      repair_v9_injections.py                vs the repair_v7 nodes
        I1d WP5       wp5_imf_normalization_repair_v9_replay vs repair_v8
        I1e WP7       wp7_ledger_repair_v9_replay baseline   vs repair_v8 (8.36)
  I2  anchor masses are per branch and read at the repair_v9 headline ages
  I3  every pre-registered input and code hash still matches (code changes
      pass only with a recorded deviation)
  I4  no repair_v9 product consumed a v8, v5 or unversioned age product, or any
      wp10_inputs.FORBIDDEN artifact
  I5  the age scan weighted by the headline posterior reproduces the headline
      per-subgroup N_death within max(0.5, 15 %)

Run:  PYTHONPATH=scripts python3 scripts/repair_v9_integrity.py I1a [I1b ...]
"""
from __future__ import annotations

import json
import re
import sys
from datetime import datetime, timezone

import numpy as np
import pandas as pd

import wp5_common as w
import wp5_joint_age_fit as J

PREREG = w.PROVENANCE / "repair_v9_prereg.json"
DEVIATIONS = w.PROVENANCE / "repair_v9_deviations.json"
OUT = w.PROVENANCE / "repair_v9_integrity.json"
HEADLINE_AGES = "wp4_age_posteriors_repair_v9_headline.parquet"
BASELINE = dict(family="PARSEC", R_V=3.1, alpha=2.3, sf_duration_Myr=0.0,
                explodability="all_explode")

# ---- frozen tolerances -----------------------------------------------------
TOL = {
    "I1a_anchor_abs": 1e-9,                 # Msun / Myr / mag, any numeric column
    "I1b_mass_rel": 1e-3,                   # per (star, branch) summary entry ...
    "I1b_mass_frac_beyond": 1e-3,           # ... at most 0.1 % of entries beyond it
    "I1b_expected_gt8_abs": 0.5,            # sum of P(M>8), stars, baseline branch
    "I1c_draw_rel": 1e-6,                   # recovered-mass draws equal to 1e-6 ...
    "I1c_draw_frac_equal": 0.99,            # ... on at least 99 % of entries per node
    "I1c_curve_abs": 0.01,                  # isotonic recovery curve, max |diff|
    "I1d_k_rel": 0.01,                      # k_median, every one of 54 cells
    "I1d_gate_flips_max": 2,                # residual_gate_pass may differ in <= 2 cells
    "I1e_ndeath_abs": 0.10,                 # baseline N_death mean, association and subgroups
    "I5_abs": 0.5, "I5_rel": 0.15,
}


def load_out() -> dict:
    return json.loads(OUT.read_text()) if OUT.exists() else {"checks": {}}


def save(name: str, result: dict) -> None:
    out = load_out()
    result["run_utc"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    out["checks"][name] = result
    out.update({"script": "scripts/repair_v9_integrity.py",
                "preregistration": str(PREREG.relative_to(w.ROOT)),
                "preregistration_sha256": w.sha256(PREREG) if PREREG.exists() else None,
                "tolerances": TOL})
    w.write_json(OUT, out)
    print(f"{name}: {result.get('verdict', result.get('pass'))}")


def verdict(exact: bool, within: bool) -> str:
    return "PASS_EXACT" if exact else ("PASS_WITHIN_TOLERANCE" if within else "FAIL")


def numeric_diff(a: pd.DataFrame, b: pd.DataFrame, key: str) -> dict:
    a, b = a.set_index(key).sort_index(), b.set_index(key).sort_index()
    if not a.index.equals(b.index):
        return {"rows_match": False}
    out = {"rows_match": True, "columns": {}}
    for col in a.columns:
        if col not in b.columns or not pd.api.types.is_numeric_dtype(a[col]):
            continue
        x, y = a[col].to_numpy(float), b[col].to_numpy(float)
        nan_same = bool(np.array_equal(np.isnan(x), np.isnan(y)))
        d = np.abs(x - y)[~np.isnan(x) & ~np.isnan(y)]
        rel = (d / np.maximum(np.abs(y[~np.isnan(x) & ~np.isnan(y)]), 1e-300)) if len(d) else d
        out["columns"][col] = {"nan_pattern_same": nan_same,
                               "max_abs": float(d.max()) if len(d) else 0.0,
                               "frac_rel_gt_tol": float(np.mean(rel > TOL["I1b_mass_rel"])) if len(rel) else 0.0}
    return out


# ---- I1 ----------------------------------------------------------------------
def I1a() -> None:
    a = pd.read_parquet(w.PROC / "wp4_anchor_hrd_repair_v9_replay.parquet")
    b = pd.read_parquet(w.PROC / "wp4_anchor_hrd_repair_v8.parquet")
    d = numeric_diff(a, b, "source_id")
    cols = d.get("columns", {})
    worst = max((c["max_abs"] for c in cols.values()), default=0.0)
    nan_ok = all(c["nan_pattern_same"] for c in cols.values())
    exact = d["rows_match"] and nan_ok and worst == 0.0
    within = d["rows_match"] and nan_ok and worst <= TOL["I1a_anchor_abs"]
    save("I1a", {"verdict": verdict(exact, within), "pass": exact or within,
                 "rows_match": d["rows_match"], "nan_pattern_same": nan_ok,
                 "max_abs_any_column": worst, "columns_compared": len(cols)})


def I1b() -> None:
    a = pd.read_parquet(w.PROC / "wp4_mass_posteriors_repair_v9_replay.parquet")
    b = pd.read_parquet(w.PROC / "wp4_mass_posteriors_repair_v8.parquet")
    d = numeric_diff(a, b, "source_id")
    cols = d.get("columns", {})
    mass_cols = [c for c in cols if c.startswith("mass_")]
    frac = max((cols[c]["frac_rel_gt_tol"] for c in mass_cols), default=0.0)
    nan_ok = all(cols[c]["nan_pattern_same"] for c in mass_cols)
    gt8 = abs(float(a["mass_baseline_p_gt8"].sum()) - float(b["mass_baseline_p_gt8"].sum()))
    sa = np.load(w.PROC / "wp4_mass_posterior_samples_repair_v9_replay.npz")["samples"]
    sb = np.load(w.PROC / "wp4_mass_posterior_samples_repair_v8.npz")["samples"]
    cube_identical = bool(sa.shape == sb.shape and np.array_equal(sa, sb, equal_nan=True))
    worst = max((cols[c]["max_abs"] for c in cols), default=0.0)
    exact = d["rows_match"] and cube_identical and worst == 0.0 and nan_ok
    within = (d["rows_match"] and nan_ok and frac <= TOL["I1b_mass_frac_beyond"]
              and gt8 <= TOL["I1b_expected_gt8_abs"])
    save("I1b", {"verdict": verdict(exact, within), "pass": exact or within,
                 "rows_match": d["rows_match"], "sample_cube_identical": cube_identical,
                 "max_frac_entries_beyond_rel_tol": frac, "nan_pattern_same": nan_ok,
                 "max_abs_any_column": worst,
                 "baseline_expected_gt8_abs_diff": gt8})


def I1c() -> None:
    ages = pd.read_parquet(w.PROC / "wp4_age_posteriors_repair_v5.parquet")
    native = J.native_isochrone_ages("PARSEC")
    nodes_out, ok_all, exact_all = [], True, True
    for sg in w.SUBGROUPS:
        for age in J.truth_age_nodes(ages, sg, "PARSEC", 3.1, native, snap=False):
            ra = pd.read_parquet(J.node_response_path(sg, "PARSEC", 3.1, age, "repair_v9_replay"))
            rb = pd.read_parquet(J.node_response_path(sg, "PARSEC", 3.1, age, "repair_v7"))
            ca = pd.read_parquet(J.node_curve_path(sg, "PARSEC", 3.1, age, "repair_v9_replay"))
            cb = pd.read_parquet(J.node_curve_path(sg, "PARSEC", 3.1, age, "repair_v7"))
            draws = [c for c in rb.columns if c.startswith("recovered_mass_draw_")]
            x, y = ra[draws].to_numpy(float), rb[draws].to_numpy(float)
            same_shape = x.shape == y.shape
            if same_shape:
                both = np.isfinite(x) & np.isfinite(y)
                equal = (np.isnan(x) & np.isnan(y)) | (both & (np.abs(x - y) <= TOL["I1c_draw_rel"] * np.abs(y)))
                frac = float(equal.mean())
                identical = bool(np.array_equal(x, y, equal_nan=True))
            else:
                frac, identical = 0.0, False
            cdiff = float(np.nanmax(np.abs(ca.sort_values("primary_mass").recovery_isotonic.to_numpy(float)
                                           - cb.sort_values("primary_mass").recovery_isotonic.to_numpy(float))))
            ok = same_shape and frac >= TOL["I1c_draw_frac_equal"] and cdiff <= TOL["I1c_curve_abs"]
            ok_all &= ok
            exact_all &= identical and cdiff == 0.0
            nodes_out.append({"subgroup": sg, "age": round(age, 4), "identical": identical,
                              "frac_draws_equal": frac, "curve_max_abs_diff": cdiff, "pass": ok})
    save("I1c", {"verdict": verdict(exact_all, ok_all), "pass": ok_all, "nodes": nodes_out})


def I1d() -> None:
    a = pd.read_parquet(w.PROC / "wp5_imf_normalization_repair_v9_replay.parquet")
    b = pd.read_parquet(w.PROC / "wp5_imf_normalization_repair_v8.parquet")
    key = ["subgroup", "family", "R_V", "alpha"]
    m = a.merge(b, on=key, suffixes=("_a", "_b"), validate="one_to_one")
    rel = (m.k_median_a - m.k_median_b).abs() / m.k_median_b
    flips = int((m.residual_gate_pass_a.astype(bool) != m.residual_gate_pass_b.astype(bool)).sum())
    num = [c for c in b.columns if c not in key and pd.api.types.is_numeric_dtype(b[c])]
    exact = len(m) == 54 and all(np.array_equal(m[f"{c}_a"].to_numpy(float), m[f"{c}_b"].to_numpy(float),
                                                 equal_nan=True) for c in num)
    within = len(m) == 54 and float(rel.max()) <= TOL["I1d_k_rel"] and flips <= TOL["I1d_gate_flips_max"]
    save("I1d", {"verdict": verdict(exact, within), "pass": exact or within, "cells": int(len(m)),
                 "k_median_max_rel_diff": float(rel.max()), "residual_gate_flips": flips})


def ledger_baseline(path) -> dict:
    l = pd.read_csv(path)
    sel = l
    for k, v in BASELINE.items():
        sel = sel[np.isclose(sel[k], v)] if isinstance(v, float) else sel[sel[k].eq(v)]
    return {r.subgroup: float(r.N_SN_mean) for r in sel.itertuples()}


def I1e() -> None:
    a = ledger_baseline(w.TABLES / "wp7_ledger_repair_v9_replay.csv")
    b = ledger_baseline(w.TABLES / "wp7_ledger_repair_v8.csv")
    diff = {k: abs(a[k] - b[k]) for k in b}
    exact = all(v == 0.0 for v in diff.values())
    within = all(v <= TOL["I1e_ndeath_abs"] for v in diff.values())
    save("I1e", {"verdict": verdict(exact, within), "pass": exact or within,
                 "replay": a, "repair_v8": b, "abs_diff": diff})


# ---- I2 ----------------------------------------------------------------------
def I2() -> None:
    anc = pd.read_parquet(w.PROC / "wp4_anchor_hrd_repair_v9.parquet")
    head = pd.read_parquet(w.PROC / HEADLINE_AGES)
    base = head[np.isclose(head.f_bin, 0.4) & np.isclose(head.dmu, 0.0) & head.indicator.eq("ums")]
    rows, ok = [], True
    for fam in w.FAMILIES:
        native = J.native_isochrone_ages(fam)
        snap = lambda a: float(native[np.argmin(np.abs(native - a))])  # noqa: E731
        for rv in w.R_V_BRANCHES:
            b = base[base.family.eq(fam) & np.isclose(base.R_V, rv)]
            exp = {r.subgroup: snap(r.age_map) for r in b.itertuples()}
            ens = snap(float(b.age_map.median()))
            used = anc[f"age_used_{fam}_rv{rv:.1f}"]
            want = anc.subgroup.map(exp).fillna(ens)
            bad = int((~np.isclose(used, want)).sum())
            finite = int(anc[f"mass_{fam}_rv{rv:.1f}"].notna().sum())
            rows.append({"family": fam, "R_V": rv, "anchors": int(len(anc)),
                         "age_mismatches": bad, "finite_masses": finite})
            ok &= bad == 0
    distinct = anc[[c for c in anc.columns if re.match(r"mass_(PARSEC|MIST)_rv", c)]].T.nunique().gt(1).mean()
    save("I2", {"pass": bool(ok), "by_branch": rows,
                "fraction_anchors_with_branch_dependent_mass": float(distinct)})


# ---- I3 ----------------------------------------------------------------------
def I3() -> None:
    pre = json.loads(PREREG.read_text())
    devs = json.loads(DEVIATIONS.read_text())["deviations"] if DEVIATIONS.exists() else []
    allowed = {(d["path"], d["new_sha256"]) for d in devs}
    moved_data, moved_code, excused = {}, {}, {}
    for name, e in pre["consumed_inputs"].items():
        now = w.sha256(w.ROOT / e["path"])
        if now != e["sha256"]:
            moved_data[e["path"]] = now
    for path, sha in pre["frozen_code"].items():
        now = w.sha256(w.ROOT / path)
        if now != sha:
            (excused if (path, now) in allowed else moved_code)[path] = now
    save("I3", {"pass": not moved_data and not moved_code, "inputs_checked": len(pre["consumed_inputs"]),
                "code_checked": len(pre["frozen_code"]), "moved_inputs": moved_data,
                "moved_code_without_deviation": moved_code, "code_changes_with_recorded_deviation": excused})


# ---- I4 ----------------------------------------------------------------------
AGE_REF = re.compile(r"wp4_age_posteriors(_[A-Za-z0-9_]+)?\.parquet")


def I4() -> None:
    import wp10_inputs as I
    forbidden = set(I.FORBIDDEN)
    bad, checked = [], 0
    for p in sorted(w.PROVENANCE.glob("*repair_v9*.json")):
        name = p.name
        if any(s in name for s in ("prereg", "integrity", "deviations", "score")):
            continue
        text = p.read_text(encoding="utf-8")
        checked += 1
        refs = {m.group(0) for m in AGE_REF.finditer(text)}
        if "replay" in name:
            allowed = {"wp4_age_posteriors_repair_v5.parquet"}
        elif "scan" in name:
            allowed = {f"wp4_age_posteriors_repair_v9_scan{i:02d}.parquet" for i in range(11)}
        else:
            allowed = {HEADLINE_AGES}
        # the Stage 1 table is a legitimate input of the headline builder only
        if name == "repair_v9_headline_ages_execution.json":
            allowed = allowed | {"wp4_age_posteriors_repair_v9.parquet"}
        for r in refs - allowed:
            bad.append({"record": name, "age_product": r})
        for f in forbidden:
            if f in text:
                bad.append({"record": name, "forbidden": f})
    static = []
    for s in ("repair_v9_injections.py", "repair_v9_age_scan.py", "repair_v9_headline_ages.py"):
        text = (w.ROOT / "scripts" / s).read_text()
        for m in AGE_REF.finditer(text):
            if m.group(1) in (None, "_repair_v5", "_repair_v8"):
                static.append({"script": s, "literal": m.group(0)})
    save("I4", {"pass": not bad and not static, "records_checked": checked,
                "violations": bad, "static_literals": static})


# ---- I5 ----------------------------------------------------------------------
def I5() -> None:
    from wp7_ledger import draw_key
    scan = pd.read_csv(w.TABLES / "repair_v9_age_scan.csv")
    head = ledger_cells(w.TABLES / "wp7_ledger_repair_v9.csv")
    draws = np.load(w.PROC / "wp5_imf_posterior_draws_repair_v9.npz")
    rows, ok = [], True
    for fam in w.FAMILIES:
        for sg in w.SUBGROUPS:
            s = scan[scan.family.eq(fam) & np.isclose(scan.R_V, 3.1) & np.isclose(scan.alpha, 2.3)
                     & np.isclose(scan.sf_duration_Myr, 0.0) & scan.subgroup.eq(sg)].sort_values("age_Myr")
            ages = draws[f"truth_age_draws__{draw_key(sg, fam, 3.1, 2.3)}"]
            weighted = float(np.mean(np.interp(ages, s.age_Myr, s.N_death_mean)))
            h = head[(fam, sg)]
            tol = max(TOL["I5_abs"], TOL["I5_rel"] * h)
            good = abs(weighted - h) <= tol
            ok &= good
            rows.append({"family": fam, "subgroup": sg, "scan_weighted": weighted,
                         "headline": h, "tolerance": tol, "pass": bool(good)})
    save("I5", {"pass": bool(ok), "cells": rows})


def ledger_cells(path) -> dict:
    l = pd.read_csv(path)
    sel = l[l.scope.eq("subgroup") & np.isclose(l.R_V, 3.1) & np.isclose(l.alpha, 2.3)
            & np.isclose(l.sf_duration_Myr, 0.0) & l.explodability.eq("all_explode")]
    return {(r.family, r.subgroup): float(r.N_SN_mean) for r in sel.itertuples()}


CHECKS = {"I1a": I1a, "I1b": I1b, "I1c": I1c, "I1d": I1d, "I1e": I1e,
          "I2": I2, "I3": I3, "I4": I4, "I5": I5}

if __name__ == "__main__":
    names = sys.argv[1:] or list(CHECKS)
    for n in names:
        CHECKS[n]()
